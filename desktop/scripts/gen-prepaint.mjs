/**
 * Emit `public/prepaint.js` from `src/lib/axes.json`.
 *
 * Why a generator rather than a hand-written script: the ten axes must be applied
 * to <html> BEFORE the first paint, which rules out a module script (deferred) and
 * therefore rules out importing the registry at runtime. The alternative to
 * generating is retyping the table in a second file, and a second table drifts -
 * that is exactly the failure the one-table rule exists to prevent. So the table
 * stays in one place and this writes the pre-paint copy from it, every build.
 *
 * Run by `predev` and `prebuild`. `--check` verifies the committed output matches
 * without writing, which is what CI runs.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const registry = JSON.parse(readFileSync(join(root, 'src/lib/axes.json'), 'utf8'));
const out = join(root, 'public/prepaint.js');

const payload = JSON.stringify({
  storageKey: registry.storageKey,
  axes: registry.axes.map((a) => ({ key: a.key, attr: a.attr, def: a.def, values: a.values.map((v) => v.value) })),
});

const script = `/* GENERATED by scripts/gen-prepaint.mjs from src/lib/axes.json - do not edit.
   Loaded synchronously from <head>, so the axis pass runs before the body is
   parsed and therefore before first paint. Appearance applied late is a colour
   flash; density or text size applied late is a reflow. */
(function () {
  'use strict';
  var R = ${payload};
  var prefs = {};
  try {
    var raw = localStorage.getItem(R.storageKey);
    if (raw) { var p = JSON.parse(raw); prefs = (p && typeof p === 'object' && 'v' in p) ? (p.v || {}) : (p || {}); }
  } catch (e) { prefs = {}; }

  var url = {};
  try {
    var q = new URLSearchParams(location.search);
    R.axes.forEach(function (a) {
      var v = q.get(a.key);
      if (v && a.values.indexOf(v) !== -1) url[a.key] = v;   // shown, never persisted
    });
  } catch (e) { /* ignore */ }

  function value(a) {
    if (a.key in url) return url[a.key];
    var v = prefs[a.key];
    return a.values.indexOf(v) !== -1 ? v : a.def;
  }

  var el = document.documentElement;
  var appearance = 'dark';
  R.axes.forEach(function (a) {
    var v = value(a);
    el.setAttribute(a.attr, v);
    if (a.key === 'theme') {
      if (v === 'system') {
        try { appearance = matchMedia('(prefers-color-scheme: light)').matches ? 'light' : 'dark'; }
        catch (e) { appearance = 'dark'; }
      } else { appearance = v; }
    }
  });
  el.setAttribute('data-appearance', appearance);
  el.style.colorScheme = appearance;
  window.__wsPrepaintAxes = R.axes.length;
})();
`;

if (process.argv.includes('--check')) {
  if (!existsSync(out)) {
    console.error('public/prepaint.js is missing - run `yarn gen:prepaint`');
    process.exit(1);
  }
  const have = readFileSync(out, 'utf8');
  if (have !== script) {
    console.error('public/prepaint.js is stale - src/lib/axes.json changed. Run `yarn gen:prepaint`.');
    process.exit(1);
  }
  console.log(`prepaint.js matches axes.json (${registry.axes.length} axes)`);
} else {
  writeFileSync(out, script);
  console.log(`wrote public/prepaint.js from ${registry.axes.length} axes`);
}
